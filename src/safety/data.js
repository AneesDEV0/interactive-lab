export function byId(id) {
  if (!id) return items[0];
  return items.find(d => d.id === id || d.id.toLowerCase() === id.toLowerCase()) || items[0];
}

/**
 * فحص وتصنيف السلوك هل هو آمن أم خطر
 */
export function testClassification(itemId, targetCategoryId) {
  const item = byId(itemId);
  const target = categories[targetCategoryId];

  if (!item || !target) {
    return {
      ok: false,
      text: 'اختر سلوكاً وحاوية تصنيف صحيحة للمتابعة.',
      item,
      target
    };
  }

  const ok = item.category === targetCategoryId;
  const isSafe = item.category === 'safe';

  let text = '';
  if (ok) {
    text = `${item.result} ${item.goldenRule}`;
  } else {
    if (isSafe) {
      text = `انتبه يا بطل! (${item.name}) هو في الحقيقة تصرف آمن وصحيح 🛡️✅ يحمينا ويقي من أخطار الصعق! ضعه في عمود السلوكيات الآمنة.`;
    } else {
      text = `تحذير عاجل! (${item.name}) تصرف شديد الخطورة ⚠️❌ قد يسبب الصعق الكهربائي والحرائق! ضعه في عمود السلوكيات الخطرة.`;
    }
  }

  return { ok, text, item, target };
}

