/**
 * توليد تقرير التقييم النهائي ورتبة حارس الأمان
 */
export function generateSafetyReport({ totalItems, attempts, elapsedSeconds }) {
  const safeTotal = Math.max(totalItems || items.length, 1);
  const safeAttempts = Math.max(attempts || safeTotal, safeTotal);
  const accuracy = Math.round((safeTotal / safeAttempts) * 100);

  let rank = '';
  let badgeTitle = '';
  let evaluation = '';
  let advice = '';

  if (accuracy >= 90) {
    rank = 'حارس الأمان الذهبي المعتمد 🛡️🌟';
    badgeTitle = 'وسام بطل السلامة والوقاية فائق التميز';
    evaluation = 'وعي استثنائي وحس أمني متقدم جداً! لقد نجحت في كشف جميع السلوكيات الخطرة وفصلتها عن السلوكيات الآمنة بدقة متناهية، وأنت الآن مؤهل لتكون سفير الأمان في بيتك ومدرستك.';
    advice = 'استمر في نشر قواعد السلامة: لا نلمس الكهرباء بالماء، ولا نكدس المقابس، ونفصل الأجهزة فور الانتهاء منها!';
  } else if (accuracy >= 75) {
    rank = 'مفتش أمان متمرس 🏅';
    badgeTitle = 'وسام حامي المنازل من الأخطار';
    evaluation = 'أداء رائع ومستوى وعي متميز! لقد استوعبت معظم قواعد الحماية وميزت بين الخطر والأمان بكفاءة عالية.';
    advice = 'تذكر دائماً: الماء والمعادن ينقلان الكهرباء إلينا، بينما البلاستيك والمطاط والجفاف يحفظون حياتنا.';
  } else {
    rank = 'مستكشف سلامة صاعد 🌱';
    badgeTitle = 'وسام المثابر في حماية الحياة';
    evaluation = 'محاولة شجاعة وبداية طيبة نحو تعلم قواعد السلامة! لقد صنفت المواقف بنجاح بعد محاولات وتفكير.';
    advice = 'راجع وضع "تعرّف" لترسيخ القواعد الذهبية لحماية الحياة، فالوعي هو درع النجاة الأول من حوادث الكهرباء!';
  }

  const safeSec = Math.max(elapsedSeconds || 0, 0);
  const minutes = Math.floor(safeSec / 60);
  const seconds = safeSec % 60;
  const timeFormatted = minutes > 0 ? `${minutes} دقيقة و ${seconds} ثانية` : `${seconds} ثانية`;

  return {
    rank,
    badgeTitle,
    accuracy,
    attempts: safeAttempts,
    totalItems: safeTotal,
    timeFormatted,
    evaluation,
    advice,
    date: new Date().toLocaleDateString('ar-EG', { year: 'numeric', month: 'long', day: 'numeric' })
  };
}

/**
 * المحرك الذكي للإجابة عن أسئلة الطالب الخاصة بالسلامة والأمان
 */
export function answer(query, currentItem) {
  const raw = (query || '').toLowerCase().trim();
  const item = currentItem || items[0];
  const isSafe = item.category === 'safe';

  if (!raw) {
    return {
      key: 'clarify',
      text: 'تفضل بسؤالي يا بطل! يمكنك سؤالي: هل هذا السلوك آمن أم خطر؟ ما سبب الخطر؟ ما القاعدة الذهبية؟ أو كيف نتصرف في المنزل.'
    };
  }

  // توحيد الحروف العربية (الهمزات والتاء المربوطة والألف اللينة) لضمان دقة المطابقة
  const q = raw
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي');

  // تلميح
  if (q.includes('تلميح') || q.includes('ساعد') || q.includes('وين') || q.includes('اين') || q.includes('كيف اصنف')) {
    return {
      key: 'hint',
      text: item.hint
    };
  }

  // القاعدة الذهبية
  if (q.includes('قاعد') || q.includes('ذهب') || q.includes('نصيح') || q.includes('كيف احمي') || q.includes('حل')) {
    return {
      key: 'golden_rule',
      text: item.goldenRule
    };
  }

  // أسئلة الماء والبلل
  if (q.includes('ماء') || q.includes('مبلل') || q.includes('بلل') || q.includes('حمام') || q.includes('غسيل') || q.includes('وضوء') || q.includes('رطب')) {
    return {
      key: 'water_danger',
      text: 'الماء يحتوي على أملاح ذائبة تجعله موصلاً سريعاً للكهرباء! لمس القابس بيد مبللة يسمح للتيار باختراق الجسم فوراً والتسبب في صعق مميت.'
    };
  }

  // أسئلة المعادن والمقص
  if (q.includes('مقص') || q.includes('معدن') || q.includes('مسمار') || q.includes('حديد') || q.includes('دبوس')) {
    return {
      key: 'metal_danger',
      text: 'المعادن والفلزات موصلات ممتازة للكهرباء! إدخال أي أداة معدنية في المقبس يفتح طريقاً مباشراً لدخول الكهرباء إلى يدك وجسدك.'
    };
  }

  // أسئلة الأطفال
  if (q.includes('طفل') || q.includes('اطفال') || q.includes('صغير') || q.includes('رضيع') || q.includes('اخي')) {
    return {
      key: 'kids_safety',
      text: 'لحماية الأطفال: نغلق المقابس بأغطية بلاستيكية عازلة، نرفع الأسلاك عن الأرض، ولا نترك الشواحن في المقابس بعد الشحن أبداً!'
    };
  }

  // ماذا يحدث عند الصعق؟
  if (q.includes('صعق') || q.includes('صدم') || q.includes('كهرب') || q.includes('ماس') || q.includes('حريق')) {
    return {
      key: 'shock_effect',
      text: 'التيار الكهربائي في مقابس المنازل (٢٢٠ فولت) قوي جداً؛ يسبب توقف نبضات القلب وحروقاً بالغة، لذا الوقاية والأمان هما خيارنا الوحيد!'
    };
  }

  // هل هذا آمن أم خطر؟
  if (q.includes('امن') || q.includes('خطر') || q.includes('صحيح') || q.includes('غلط') || q.includes('خطا')) {
    if (isSafe) {
      return {
        key: 'is_safe',
        text: `هذا سلوك آمن وصحيح 🛡️✅! لأنه يمنع وصول الشحنات ويحافظ على سلامة الأجهزة وأرواحنا.`
      };
    } else {
      return {
        key: 'is_hazard',
        text: `هذا سلوك خطر وخاطئ جداً ⚠️❌! درجة خطورته: (${item.dangerLevel}) ويجب تجنبه تماماً لحماية النفس.`
      };
    }
  }

  // رد افتراضي مرتبط بالموقف الحالي
  return {
    key: 'item_general',
    text: `${item.name}: ${item.fact} ${item.goldenRule}`
  };
}
