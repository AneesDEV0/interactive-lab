/**
 * دالة جلب عنصر بواسطة المعرف
 */
export const byId = id => items.find(item => item.id === id);

/**
 * دالة جلب عناصر تصنيف معين
 */
export const byCategory = catId => items.filter(item => item.category === catId);

/**
 * دالة فحص وتصنيف العنصر داخل الحاوية المستهدفة
 * @param {string} itemId 
 * @param {string} targetCategoryId 
 * @returns {{ ok: boolean, text: string, item: object, target: object }}
 */
export function testClassification(itemId, targetCategoryId) {
  const item = byId(itemId);
  const target = categories[targetCategoryId];
  if (!item || !target) {
    return {
      ok: false,
      text: 'اختر عنصراً من القائمة وحاوية مناسبة لتجربة الفرز.'
    };
  }

  const ok = item.category === targetCategoryId;
  return {
    ok,
    item,
    target,
    text: ok ? item.result : `${item.hint} (أنت اخترت: ${target.name})`
  };
}

