export function normalizeArabic(text) {
  return String(text ?? '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '') // إزالة التشكيل والتطويل
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/[ىئ]/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ') // إزالة الرموز كـ = + - _ /
    .replace(/\s+/g, ' ')
    .trim();
}

// حساب مسافة ليفنشتاين للتسامح مع الأخطاء الإملائية
export function levenshteinDistance(a, b) {
  if (!a || !b) return (a || '').length + (b || '').length;
  if (a === b) return 0;
  const matrix = [];
  for (let i = 0; i <= b.length; i++) matrix[i] = [i];
  for (let j = 0; j <= a.length; j++) matrix[0][j] = j;

  for (let i = 1; i <= b.length; i++) {
    for (let j = 1; j <= a.length; j++) {
      if (b.charAt(i - 1) === a.charAt(j - 1)) {
        matrix[i][j] = matrix[i - 1][j - 1];
      } else {
        matrix[i][j] = Math.min(
          matrix[i - 1][j - 1] + 1,
          matrix[i][j - 1] + 1,
          matrix[i - 1][j] + 1
        );
      }
    }
  }
  return matrix[b.length][a.length];
}

// فحص وجود كلمة مطابقة أو شبيهة بأخطاء مطبعية
function matchesFuzzyToken(tokens, targetList, maxDist = 1) {
  return tokens.some(tok => {
    // إزالة البادئات الشائعة (ال، و، ف، ب، ك، ل)
    const stripped = tok.replace(/^(?:ال|وال|فال|بال|كال|لل|و|ف|ب|ل)/, '');
    return targetList.some(target => {
      if (tok === target || stripped === target) return true;
      if (tok.includes(target) || (target.length >= 4 && stripped.includes(target))) return true;
      // تسامح بالأخطاء الإملائية البسيطة إذا كانت الكلمة أطول من 3 أحرف
      if (target.length >= 4) {
        if (Math.abs(tok.length - target.length) <= 1 && levenshteinDistance(tok, target) <= maxDist) return true;
        if (Math.abs(stripped.length - target.length) <= 1 && levenshteinDistance(stripped, target) <= maxDist) return true;
      }
      return false;
    });
  });
}

