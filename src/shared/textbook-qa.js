export function findTextbookAnswer(query) {
  if (!query || typeof query !== 'string') return null;
  const qClean = normalizeArabic(query);
  if (!qClean || qClean.length < 2) return null;

  // 1. فحص الأنماط المباشرة Regex
  for (const entry of TEXTBOOK_ENTRIES) {
    if (entry.patterns && entry.patterns.some(r => r.test(qClean) || r.test(query))) {
      return { id: entry.id, text: entry.answer };
    }
  }

  // 2. فحص الكلمات المفتاحية والمطابقة المرنة Fuzzy Tokens
  const tokens = qClean.split(/\s+/).filter(Boolean);
  for (const entry of TEXTBOOK_ENTRIES) {
    if (entry.keywords) {
      const allGroupsMatch = entry.keywords.every(group => matchesFuzzyToken(tokens, group, 1));
      if (allGroupsMatch) {
        return { id: entry.id, text: entry.answer };
      }
    }
  }

  return null;
}
