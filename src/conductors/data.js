/**
 * توليد التقرير النهائي التفاعلي للبروفيسور
 */
export function generateProfessorReport({ totalItems, attempts, elapsedSeconds }) {
  const accuracy = Math.round((totalItems / Math.max(attempts, totalItems)) * 100);
  let rank = '';
  let badgeTitle = '';
  let evaluation = '';
  let advice = '';

  if (accuracy >= 90) {
    rank = 'عبقري الدارات الكهربائية 🌟';
    badgeTitle = 'وسام العالم الصغير فائق التميز';
    evaluation = 'أداء استثنائي ودقة علمية متناهية! لقد استوعبت تماماً الفارق الجوهري بين المواد الموصلة التي تمرر الكهرباء في الدارات والمواد العازلة التي تقينا أخطار الصعق.';
    advice = 'استمر في شغفك العلمي يا بطل، فأنت مؤهل لتكون أحد كبار علماء الفيزياء والتكنولوجيا في المستقبل!';
  } else if (accuracy >= 75) {
    rank = 'باحث علمي متمرس 🏅';
    badgeTitle = 'وسام باحث الكهرباء المتميز';
    evaluation = 'إنجاز رائع ومستوى فهم عميق! لقد ميزت معظم المواد بكفاءة ونجحت في فرزها داخل الجدول الثنائي بإتقان.';
    advice = 'تذكر دائماً: الفلزات اللامعة كالنحاس والحديد هي موصلات الكهرباء، بينما البلاستيك والمطاط والخشب هي حراس الأمان العازلون.';
  } else {
    rank = 'مستكشف صاعد شجاع 🌱';
    badgeTitle = 'وسام المستكشف والمثابر العلمي';
    evaluation = 'محاولة مشجعة ومثابرة جميلة! لقد خضت التجربة وجمعت كل العناصر في الجدول بنجاح بعد محاولات علمية جادة.';
    advice = 'راجع وضع "تعرّف" مرة أخرى لتقوية ملاحظتك العلمية لخامات التوصيل والعزل، فالتكرار يصنع العلماء!';
  }

  const minutes = Math.floor(elapsedSeconds / 60);
  const seconds = elapsedSeconds % 60;
  const timeFormatted = minutes > 0 ? `${minutes} دقيقة و ${seconds} ثانية` : `${seconds} ثانية`;

  return {
    rank,
    badgeTitle,
    accuracy,
    attempts,
    totalItems,
    timeFormatted,
    evaluation,
    advice,
    date: new Date().toLocaleDateString('ar-EG', { year: 'numeric', month: 'long', day: 'numeric' })
  };
}
