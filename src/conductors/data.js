/**
 * توليد تقرير التقييم النهائي التفاعلي للبروفيسور مع حفظ التقدم
 */
export function generateProfessorReport({ totalItems, attempts, elapsedSeconds }) {
  const safeTotal = Math.max(totalItems || items.length, 1);
  const safeAttempts = Math.max(attempts || safeTotal, safeTotal);
  const accuracy = Math.round((safeTotal / safeAttempts) * 100);

  let rank = '';
  let badgeTitle = '';
  let evaluation = '';
  let advice = '';

  if (accuracy >= 90) {
    rank = 'عبقري الدارات الكهربائية 🌟';
    badgeTitle = 'وسام العالم الصغير فائق التميز';
    evaluation = 'أداء استثنائي ودقة علمية متناهية! لقد استوعبت تماماً الفارق الجوهري بين المواد الموصلة التي تكمل الدارة وتضيء المصباح، والمواد العازلة التي تقينا أخطار الصعق.';
    advice = 'استمر في شغفك العلمي يا بطل الصف الرابع، فأنت مؤهل لتكون أحد كبار علماء الفيزياء والتكنولوجيا في المستقبل!';
  } else if (accuracy >= 75) {
    rank = 'باحث علمي متمرس 🏅';
    badgeTitle = 'وسام باحث الكهرباء المتميز';
    evaluation = 'إنجاز رائع ومستوى فهم عميق! لقد ميزت معظم المواد بكفاءة ونجحت في فرزها داخل الجدول الثنائي بإتقان عالٍ.';
    advice = 'تذكر دائماً: الفلزات اللامعة كالحديد والنحاس والذهب والهاون موصلات تضيء المصباح، بينما البلاستيك والمطاط والخشب والزجاج حراس أمان عازلون.';
  } else {
    rank = 'مستكشف صاعد شجاع 🌱';
    badgeTitle = 'وسام المستكشف والمثابر العلمي';
    evaluation = 'محاولة مشجعة ومثابرة جميلة! لقد خضت التجربة وجمعت كل العناصر في الجدول بنجاح بعد محاولات علمية جادة.';
    advice = 'راجع وضع "تعرّف" مرة أخرى لتقوية ملاحظتك العلمية لخامات التوصيل والعزل، فالتكرار والتجربة يصنعان العلماء!';
  }

  const safeSec = Math.max(elapsedSeconds || 0, 0);
  const minutes = Math.floor(safeSec / 60);
  const seconds = safeSec % 60;
  const timeFormatted = minutes > 0 ? `${minutes} دقيقة و ${seconds} ثانية` : `${seconds} ثانية`;

  return {
    rank,
    badgeTitle,
    accuracy,
    attempts: safeAttempts,
    totalItems: safeTotal,
    timeFormatted,
    evaluation,
    advice,
    date: new Date().toLocaleDateString('ar-EG', { year: 'numeric', month: 'long', day: 'numeric' })
  };
}

/**
 * المحرك الذكي للإجابة عن أسئلة الطالب واستفساراته للبروفيسور
 */
export function answer(query, currentItem) {
  const q = (query || '').toLowerCase().trim();
  const item = currentItem || items[0];
  const isConductive = item.category === 'conductive';

  if (!q) {
    return {
      key: 'clarify',
      text: 'تفضل بسؤالي يا بطل! يمكنك سؤالي: هل هذه المادة موصلة؟ هل يضيء المصباح؟ ما الفرق بين الموصل والعازل؟ أو قواعد السلامة.'
    };
  }

  // تلميح للفرز
  if (q.includes('تلميح') || q.includes('ساعدني') || q.includes('وين احط') || q.includes('أين أضع') || q.includes('كيف اصنف')) {
    return {
      key: 'hint',
      text: item.hint
    };
  }

  // هل يضيء المصباح؟
  if (q.includes('مصباح') || q.includes('يضيء') || q.includes('ينور') || q.includes('تولع') || q.includes('دارة')) {
    if (isConductive) {
      return {
        key: 'light_on',
        text: `نعم بالتأكيد! ${item.name} مصنوع من ${item.material}، وهو يغلق الدارة الكهربائية ويسمح للشحنات بالسريان، فيضيء المصباح بقوة ⚡💡!`
      };
    } else {
      return {
        key: 'light_off',
        text: `لا، لن يضيء المصباح! لأن ${item.name} مصنوع من ${item.material} وهي خامة عازلة تمنع سريان التيار الكهربائي ويبقى مسار الدارة مفتوحاً 🛡️🔒.`
      };
    }
  }

  // هل يوصل الكهرباء أم عازل؟
  if (q.includes('موصل') || q.includes('عازل') || q.includes('كهربا') || q.includes('تيار') || q.includes('شحنات')) {
    if (isConductive) {
      return {
        key: 'conductor_answer',
        text: `${item.name} مادة موصلة للكهرباء تسمح للشحنات بالمرور بحرية، ومكانها الصحيح في عمود المواد الموصلة ⚡.`
      };
    } else {
      return {
        key: 'insulator_answer',
        text: `${item.name} مادة عازلة للكهرباء تقف سداً منيعاً وتمنع انتقال الشحنات، ومكانها في عمود المواد العازلة 🛡️.`
      };
    }
  }

  // مما يصنع؟ أو ما هي خامته؟
  if (q.includes('يصنع') || q.includes('مادة') || q.includes('خامة') || q.includes('أصل') || q.includes('من شو')) {
    return {
      key: 'material_origin',
      text: `${item.name} مصنوع من ${item.material}، وأصله: ${item.origin}. وخاصيته: ${item.properties}`
    };
  }

  // هل يوصل الحرارة؟
  if (q.includes('حرارة') || q.includes('يسخن') || q.includes('ساخن') || q.includes('طعام')) {
    return {
      key: 'thermal',
      text: `${item.name}: ${item.thermalConductivity}. وتذكر دائماً: الفلزات التي توصل الكهرباء توصل الحرارة أيضاً بسرعة!`
    };
  }

  // قواعد السلامة والأمان
  if (q.includes('سلامة') || q.includes('امان') || q.includes('أمان') || q.includes('خطر') || q.includes('صعق') || q.includes('مقبس') || q.includes('بيت')) {
    return {
      key: 'safety',
      text: `${item.safetyTip} وتذكر قاعدة البروفيسور الذهبية: لا نلمس المقابس الكهربائية بأيدٍ مبللة، ولا نستخدم أدوات معدنية قرب الكهرباء المنزلية!`
    };
  }

  // ما الفرق بين الموصل والعازل؟
  if (q.includes('الفرق') || q.includes('ما الفرق') || q.includes('شو الفرق') || q.includes('تعريف')) {
    return {
      key: 'difference',
      text: 'المواد الموصلة كالحديد والنحاس تسمح بمرور الكهرباء وتضيء المصباح، بينما المواد العازلة كالبلاستيك والخشب والمطاط تمنع مرور الكهرباء وتحمينا من الصعق!'
    };
  }

  // هل يجذبه المغناطيس؟
  if (q.includes('مغناطيس') || q.includes('يجذب')) {
    if (item.id === 'ironNail' || item.id === 'paperClip') {
      return {
        key: 'magnet_yes',
        text: `نعم! ${item.name} مصنوع من الحديد، والحديد ينجذب للمغناطيس بقوة، وهو في نفس الوقت موصل للكهرباء 🧲!`
      };
    } else {
      return {
        key: 'magnet_no',
        text: `لا يجذبه المغناطيس. فقط المواد التي تحتوي على الحديد والنيكل تنجذب للمغناطيس، بينما باقي المواد كالبلاستيك والخشب والزجاج والنحاس لا تنجذب 🧲.`
      };
    }
  }

  // رد تشجيعي افتراضي مرتبط بالعنصر
  return {
    key: 'item_general',
    text: `${item.name}: ${item.fact} ${item.hint}`
  };
}
